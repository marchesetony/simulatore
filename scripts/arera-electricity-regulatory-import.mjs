import { LocalRegulatoryRepository } from "../app/lib/foundation/regulatory-repository.ts";
import { AreraElectricityRegulatorySourceAdapter } from "../app/lib/foundation/arera-electricity-regulatory.ts";

const retrievedAt = process.env.ARERA_RETRIEVED_AT ?? new Date().toISOString();
const regulatoryRoot = "var/foundation-regulatory-data";
const tenantId = "tenant_local-demo";
const repository = new LocalRegulatoryRepository(regulatoryRoot);
const recordsBefore = await repository.getRegulatoryValues(tenantId);
const adapter = new AreraElectricityRegulatorySourceAdapter(repository, { regulatoryRoot, tenantId });
const result = await adapter.importOfficial({ retrievedAt });
const recordsAfter = await repository.getRegulatoryValues(tenantId);
const actions = result.actions.reduce((counts, action) => ({ ...counts, [action.toLowerCase()]: (counts[action.toLowerCase()] ?? 0) + 1 }), { created: 0, reused: 0, conflict: 0 });
const identities = new Set(recordsAfter.map((record) => record.identityKey));
const directXlsx = result.attachments.find((item) => item.extension === "XLSX");
const recordsFor = (code) => result.systemChargeRecords.filter((record) => record.componentCode === code);
const actionFor = (records) => records.length === 0 ? "NOT_FOUND" : records.map((record) => result.actions[result.infrastructure.records.length + result.systemChargeRecords.indexOf(record)] ?? "NOT_REPORTED").join(",");

console.log(`ARERA_575_SOURCE_FOUND=${result.infrastructure.records.length ? "SI" : "NO"}`);
console.log(`ARERA_575_PARSE=${result.infrastructure.records.length ? "PARSED" : "NOT_PARSED"}`);
console.log(`ARERA_575_EFFECTIVE_2026=${result.infrastructure.records.every((record) => record.effectiveFrom <= "2026-07-01" && (record.effectiveTo === null || record.effectiveTo >= "2026-07-01")) ? "OK" : "INCOMPLETE"}`);
console.log(`ARERA_227_SOURCE_FOUND=${result.documentCount ? "SI" : "NO"}`);
console.log(`ARERA_227_DOCUMENT_COUNT=${result.documentCount}`);
console.log(`ARERA_227_DOCUMENTS_INSPECTED=${result.documentsInspected.length}`);
console.log(`ARERA_227_ATTACHMENT_FOUND=${directXlsx ? "SI" : "NO"}`);
console.log(`ARERA_227_STRUCTURED_PARSE=${result.structuredParse}`);
console.log(`ARERA_227_EFFECTIVE_FROM=${result.systemChargeRecords.some((record) => record.effectiveFrom === "2026-07-01") ? "2026-07-01" : "NOT_FOUND"}`);
console.log(`ARERA_INFRASTRUCTURE_RECORDS=${result.infrastructure.records.length}`);
console.log(`ARERA_SYSTEM_CHARGE_RECORDS=${result.systemChargeRecords.length}`);
console.log(`ARERA_SYSTEM_CHARGE_MISSING=${result.missingComponentCodes.join(",") || "NONE"}`);
console.log(`UC3_SOURCE_FOUND=${recordsFor("UC3").length ? "SI" : "NO"}`);
console.log(`UC3_SOURCE_STRATEGY=${result.uc3SourceStrategy}`);
console.log(`UC3_OFFICIAL_IDENTIFIER=${recordsFor("UC3")[0]?.officialIdentifier ?? "NOT_FOUND"}`);
console.log(`UC3_EFFECTIVE_FROM=${recordsFor("UC3")[0]?.effectiveFrom ?? "NOT_FOUND"}`);
console.log(`UC3_PRIOR_SOURCE_IDENTIFIER=${result.uc3PriorSourceIdentifier ?? "NONE"}`);
console.log(`UC3_IMPORT_ACTION=${actionFor(recordsFor("UC3"))}`);
console.log(`UC6_SOURCE_FOUND=${recordsFor("UC6").length ? "SI" : "NO"}`);
console.log(`UC6_SOURCE_STRATEGY=${result.uc6SourceStrategy}`);
console.log(`UC6_OFFICIAL_IDENTIFIER=${recordsFor("UC6")[0]?.officialIdentifier ?? "NOT_FOUND"}`);
console.log(`UC6_EFFECTIVE_FROM=${recordsFor("UC6")[0]?.effectiveFrom ?? "NOT_FOUND"}`);
console.log(`UC6_PRIOR_SOURCE_IDENTIFIER=${result.uc6PriorSourceIdentifier ?? "NONE"}`);
console.log(`UC6_COMPONENT_COUNT=${recordsFor("UC6").length}`);
console.log(`UC6_IMPORT_ACTION=${actionFor(recordsFor("UC6"))}`);
console.log(`ARERA_REGULATORY_RECORD_COUNT_BEFORE=${recordsBefore.length}`);
console.log(`ARERA_REGULATORY_RECORD_COUNT_AFTER=${recordsAfter.length}`);
console.log(`REGULATORY_CREATED=${actions.created ?? 0}`);
console.log(`REGULATORY_REUSED=${actions.reused ?? 0}`);
console.log(`REGULATORY_CONFLICTS=${actions.conflict ?? 0}`);
console.log(`REGULATORY_DUPLICATES=${recordsAfter.length - identities.size}`);
console.log(`REGULATORY_BACKUP_CREATED=${result.backup ? "SI" : "NO"}`);
console.log(`REGULATORY_BACKUP_READABLE=${result.backup?.readable ? "SI" : "NO"}`);
console.log(`REGULATORY_BACKUP_RESTORE_CHECK=${result.backup?.restoreCheck ? "OK" : "FAILED"}`);
console.log(`ARERA_IMPORT_ACTIONS=${result.actions.join(",") || "NONE"}`);
